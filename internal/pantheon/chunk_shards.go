const (
	defaultUserShardRoot = "00 Pantheon Core/Weave/User Shards"
	shardGeneratedBegin  = "<!-- PANTHEON-SHARD:BEGIN -->"
	shardGeneratedEnd    = "<!-- PANTHEON-SHARD:END -->"
)

type userShardJournal struct {
	Version       string                  `json:"version"`
	RunID         string                  `json:"run_id"`
	StartedAt     string                  `json:"started_at"`
	FinishedAt    string                  `json:"finished_at,omitempty"`
	VaultPath     string                  `json:"vault_path"`
	GraphPath     string                  `json:"graph_path"`
	ShardRoot     string                  `json:"shard_root"`
	InventoryHash string                  `json:"inventory_hash"`
	Status        string                  `json:"status"`
	Entries       []weaveLinkJournalEntry `json:"entries"`
}

type userShardState struct {
	Version          string `json:"version"`
	RunID            string `json:"run_id"`
	CreatedAt        string `json:"created_at"`
	UpdatedAt        string `json:"updated_at"`
	VaultPath        string `json:"vault_path"`
	GraphPath        string `json:"graph_path"`
	ShardRoot        string `json:"shard_root"`
	InventoryHash    string `json:"inventory_hash"`
	BatchSize        int    `json:"batch_size"`
	NextOffset       int    `json:"next_offset"`
	TotalShards      int    `json:"total_shards"`
	CompletedBatches int    `json:"completed_batches"`
	JournalPath      string `json:"journal_path"`
	Status           string `json:"status"`
}

func userShardRelativePath(root, id string) string {
	return filepath.ToSlash(filepath.Join(root, id[:2], id+".md"))
}

func renderUserShard(node chunkLinkNode, text string, shardPath string, edges []chunkLinkEdge, shardPaths map[string]string) []byte {
	var b strings.Builder
	b.WriteString("---\n")
	fmt.Fprintf(&b, "pantheon_shard: user\nshard_id: %s\nsource_path: %q\nordinal: %d\n---\n\n", node.ID, node.Path, node.Ordinal)
	b.WriteString(shardGeneratedBegin + "\n\n")
	fmt.Fprintf(&b, "# User shard %s\n\nSource: [[%s|%s]]\n\n", node.ID, node.Path, strings.TrimSuffix(filepath.Base(node.Path), filepath.Ext(node.Path)))
	b.WriteString(text)
	b.WriteString("\n\n## Linked shards\n\n")
	for _, edge := range edges {
		targetID := edge.TargetID
		if edge.SourceID != node.ID {
			targetID = edge.SourceID
		}
		targetPath := shardPaths[targetID]
		if targetPath == "" {
			continue
		}
		fmt.Fprintf(&b, "- [[%s|%s]] — shared terms: `%s`; lexical score: `%.2f`\n", targetPath, targetID, strings.Join(edge.SharedTerms, ", "), edge.Score)
	}
	b.WriteString("\n> Generated by Pantheon from user-authored Nexus shards. These links are discovery candidates and preserve the source conversation above.\n\n")
	b.WriteString(shardGeneratedEnd + "\n")
	return []byte(b.String())
}

func loadUserShardState(path string) (userShardState, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return userShardState{}, err
	}
	var state userShardState
	if err := json.Unmarshal(data, &state); err != nil {
		return userShardState{}, err
	}
	if state.Version != chunkLinkGraphVersion || (state.Status != "active" && state.Status != "completed") {
		return userShardState{}, errors.New("invalid user shard materialization state")
	}
	if state.NextOffset < 0 || state.NextOffset > state.TotalShards {
		return userShardState{}, errors.New("invalid user shard materialization cursor")
	}
	return state, nil
}

func runUserShardMaterialization(statePath, graphPath, stateDir, vault, root string, batchSize, batches int) error {
	if batchSize <= 0 || batchSize > 1000 {
		return errors.New("shard batch size must be between 1 and 1000")
	}
	if batches <= 0 || batches > 1000 {
		return errors.New("shard batches must be between 1 and 1000")
	}
	graph, err := loadChunkLinkGraph(graphPath)
	if err != nil {
		return err
	}
	if graph.VaultPath != vault || graph.Authorship != "nexus_user" {
		return errors.New("chunk graph is not the current user-authored graph for this Vault")
	}
	if len(graph.Nodes) == 0 {
		return errors.New("chunk graph has no shard nodes")
	}
	root = filepath.ToSlash(strings.Trim(root, "/"))
	if root == "" || strings.HasPrefix(root, "../") || filepath.IsAbs(root) {
		return errors.New("shard root must be a non-empty Vault-relative directory")
	}

	inventory, err := buildNexusChunkInventory(vault)
	if err != nil {
		return err
	}
	fullText := map[string]string{}
	ordinals := map[string]int{}
	for _, chunk := range inventory.Chunks {
		if chunk.Authorship != "nexus_user" {
			continue
		}
		ordinal := ordinals[chunk.Path]
		ordinals[chunk.Path]++
		fullText[userChunkID(chunk.Path, ordinal)] = chunk.Text
	}
	for _, node := range graph.Nodes {
		if fullText[node.ID] == "" {
			return fmt.Errorf("graph node %s no longer resolves to a user chunk", node.ID)
		}
	}

	shardPaths := map[string]string{}
	for _, node := range graph.Nodes {
		shardPaths[node.ID] = userShardRelativePath(root, node.ID)
	}
	edgesBySource := map[string][]chunkLinkEdge{}
	for _, edge := range graph.Edges {
		edgesBySource[edge.SourceID] = append(edgesBySource[edge.SourceID], edge)
	}

	state, err := loadUserShardState(statePath)
	if err != nil {
		if !os.IsNotExist(err) {
			return err
		}
		now := time.Now().UTC()
		runID := now.Format("20060102T150405.000000000Z")
		journalPath := filepath.Join(stateDir, "shards-"+runID+".json")
		state = userShardState{Version: chunkLinkGraphVersion, RunID: runID, CreatedAt: now.Format(time.RFC3339Nano), UpdatedAt: now.Format(time.RFC3339Nano), VaultPath: vault, GraphPath: graphPath, ShardRoot: root, InventoryHash: graph.InventoryHash, BatchSize: batchSize, TotalShards: len(graph.Nodes), JournalPath: journalPath, Status: "active"}
		if err := writeJSONAtomic(statePath, state, 0o600); err != nil {
			return err
		}
	} else {
		if state.Status == "completed" {
			return fmt.Errorf("shard materialization %s is already complete; use a new --state path to rerun", state.RunID)
		}
		if state.VaultPath != vault || state.GraphPath != graphPath || state.ShardRoot != root || state.InventoryHash != graph.InventoryHash || state.TotalShards != len(graph.Nodes) {
			return errors.New("shard inputs changed; start a new materialization state")
		}
		if state.BatchSize != batchSize {
			return fmt.Errorf("existing shard materialization uses batch size %d", state.BatchSize)
		}
	}
	journalData, err := os.ReadFile(state.JournalPath)
	if err != nil && !os.IsNotExist(err) {
		return err
	}
	journal := userShardJournal{Version: chunkLinkGraphVersion, RunID: state.RunID, StartedAt: state.CreatedAt, VaultPath: vault, GraphPath: graphPath, ShardRoot: root, InventoryHash: graph.InventoryHash, Status: "running"}
	if len(journalData) > 0 {
		if err := json.Unmarshal(journalData, &journal); err != nil {
			return err
		}
	}
	backupDir := filepath.Join(stateDir, "backups", "shards-"+state.RunID)
	// If the previous foreground writer was interrupted before the state file
	// existed, recover the completed prefix without rewriting it.
	if state.NextOffset == 0 {
		for i, node := range graph.Nodes {
			rel := userShardRelativePath(root, node.ID)
			path := filepath.Join(vault, filepath.FromSlash(rel))
			before, readErr := readRegularFileNoSymlink(path)
			if readErr != nil {
				break
			}
			edges := append([]chunkLinkEdge(nil), edgesBySource[node.ID]...)
			sort.SliceStable(edges, func(a, b int) bool { return edges[a].TargetID < edges[b].TargetID })
			if !bytes.Equal(before, renderUserShard(node, fullText[node.ID], rel, edges, shardPaths)) {
				break
			}
			state.NextOffset = i + 1
		}
	}
	changed := 0
	for batch := 0; batch < batches && state.Status == "active"; batch++ {
		end := min(state.NextOffset+state.BatchSize, len(graph.Nodes))
		for i := state.NextOffset; i < end; i++ {
			node := graph.Nodes[i]
			rel := shardPaths[node.ID]
			path := filepath.Join(vault, filepath.FromSlash(rel))
			if !pathWithin(vault, path) {
				return fmt.Errorf("shard path escapes Vault: %s", rel)
			}
			edges := append([]chunkLinkEdge(nil), edgesBySource[node.ID]...)
			sort.SliceStable(edges, func(i, j int) bool { return edges[i].TargetID < edges[j].TargetID })
			after := renderUserShard(node, fullText[node.ID], rel, edges, shardPaths)
			before, readErr := readRegularFileNoSymlink(path)
			if readErr == nil {
				if !bytes.Contains(before, []byte(shardGeneratedBegin)) {
					return fmt.Errorf("refusing to overwrite non-generated shard: %s", rel)
				}
				if bytes.Equal(before, after) {
					continue
				}
			} else if !os.IsNotExist(readErr) {
				return fmt.Errorf("read shard %s: %w", rel, readErr)
			}
			if before != nil {
				if err := os.MkdirAll(backupDir, 0o700); err != nil {
					return err
				}
				backup := filepath.Join(backupDir, hashBytes([]byte(rel))+".md")
				if err := writeBytesAtomic(backup, before, 0o600); err != nil {
					return err
				}
				journal.Entries = append(journal.Entries, weaveLinkJournalEntry{Path: rel, BackupPath: backup, BeforeHash: hashBytes(before), AfterHash: hashBytes(after), Action: "updated"})
			} else {
				journal.Entries = append(journal.Entries, weaveLinkJournalEntry{Path: rel, AfterHash: hashBytes(after), Action: "created"})
			}
			if err := writeBytesAtomic(path, after, 0o600); err != nil {
				return err
			}
			changed++
		}
		state.NextOffset = end
		state.CompletedBatches++
		if state.NextOffset >= len(graph.Nodes) {
			state.Status = "completed"
		}
		state.UpdatedAt = time.Now().UTC().Format(time.RFC3339Nano)
		if err := writeJSONAtomic(statePath, state, 0o600); err != nil {
			return err
		}
		if err := writeJSONAtomic(state.JournalPath, journal, 0o600); err != nil {
			return err
		}
		fmt.Printf("Shard batch %d: %d/%d shards; changed this invocation %d\n", state.CompletedBatches, state.NextOffset, len(graph.Nodes), changed)
	}
	if state.Status == "completed" {
		indexPath := filepath.Join(vault, filepath.FromSlash(root), "User shards — Index.md")
		index := []byte(fmt.Sprintf("---\npantheon_shard_index: true\nshard_count: %d\ninventory_hash: %s\n---\n\n# User-authored shard graph\n\nThis derived layer contains %d user-authored shards from the Nexus archive. Agent-authored text is excluded. Each shard preserves its source conversation and carries crawler-generated links to related shards.\n\nGraph source: `%s`\n\n", len(graph.Nodes), graph.InventoryHash, len(graph.Nodes), graphPath))
		if err := writeBytesAtomic(indexPath, index, 0o600); err != nil {
			return err
		}
		journal.Status = "completed"
		journal.FinishedAt = time.Now().UTC().Format(time.RFC3339Nano)
		if err := writeJSONAtomic(state.JournalPath, journal, 0o600); err != nil {
			return err
		}
	}
	return nil
}
